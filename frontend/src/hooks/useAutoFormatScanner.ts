/**
 * Autonomous document-wide formatting scanner.
 *
 * Implements the spec's state machine:
 * Idle_Scanning → OffScreen_Detected → InViewport_Detected → Accepted / Rejected
 *                                                   ↕ scroll
 *                                         OffScreen_Detected
 */
export function useAutoFormatScanner({
  editor,
  enabled = true,
  minConfidence = 0.68,
  presetKey = null,
  documentId,
}: UseAutoFormatScannerOptions): {
  suggestions: ScannerSuggestion[]
  activeSuggestion: ScannerSuggestion | null
  scannerState: ScannerState
  isTargetInViewport: boolean
  dismissSuggestion: (key: string) => void
  dismissAll: () => void
  /** Clear all dismissed keys so edited blocks can be suggested again. */
  resetDismissed: () => void
  selectSuggestion: (key: string) => void
  acceptSuggestion: (key: string) => void
  rejectSuggestion: (key: string) => void
} {
  const [suggestions, setSuggestions] = useState<ScannerSuggestion[]>([])
  // Current cards for the answer callbacks below, which stay stable across renders.
  const suggestionsRef = useRef<ScannerSuggestion[]>([])
  suggestionsRef.current = suggestions

  /** Every block key a card answers for: all its members when same-fix blocks were merged. */
  const keysOf = useCallback((key: string): string[] => {
    return suggestionsRef.current.find((s) => s.key === key)?.memberKeys ?? [key]
  }, [])
  const [activeIdx, setActiveIdx] = useState<number>(-1)
  const [isTargetInViewport, setIsTargetInViewport] = useState<boolean>(true)
  const [scannerState, setScannerState] = useState<ScannerState>('Idle_Scanning')

  const scanTimerRef = useRef<ReturnType<typeof setTimeout> | null>(null)
  const dismissedRef = useRef<Set<string>>(new Set())
  // Decisions the user made in earlier sessions; unlike dismissedRef it is never cleared.
  const memoryRef = useRef<Record<string, string>>({})
  useEffect(() => {
    memoryRef.current = loadSuggestionMemory(documentId)
  }, [documentId])

  const activeSuggestion = activeIdx >= 0 && activeIdx < suggestions.length ? suggestions[activeIdx] : null

  /** Estimate which page a ProseMirror position falls on. */
  const estimatePageNumber = useCallback(
    (pos: number): number => {
      if (!editor || editor.isDestroyed) return 1
      let pageBreaks = 0
      editor.state.doc.nodesBetween(0, pos, (node) => {
        if (node.type.name === 'pageBreak' || (node.isBlock && node.type.name === 'horizontalRule')) {
          pageBreaks++
        }
      })
      if (pageBreaks > 0) return pageBreaks + 1
      // Fallback: character-ratio heuristic
      const docSize = editor.state.doc.content.size
      const ratio = docSize > 0 ? pos / docSize : 0
      const estimatedPages = Math.max(1, Math.ceil(docSize / 4000))
      return Math.min(Math.max(1, Math.round(ratio * estimatedPages) + 1), estimatedPages)
    },
    [editor]
  )

  /** Scan the document for heading-eligible paragraphs. */
  const scanDocument = useCallback(() => {
    if (!editor || editor.isDestroyed || !enabled) return

    // Yield to event loop to avoid blocking the main thread
    setTimeout(() => {
      if (!editor || editor.isDestroyed || !enabled) return
      // Never scan mid-IME-composition: the doc is in a transient state.
      if (editor.view.composing) return

      // Skip sweeps while the caret sits inside a table or code block: those
      // blocks are structural and scanning them on every keystroke is waste.
      const $caret = editor.state.selection.$from
      for (let d = $caret.depth; d >= 0; d--) {
        const name = $caret.node(d).type.name
        if (name === 'table' || name === 'codeBlock') return
      }

      // Preset-derived targets: the structural sections the active academic
      // preset expects. Unstyled blocks whose text matches a section
      // placeholder become high-confidence suggestions from the blueprint.
      const blueprint = presetKey ? getBlueprint(presetKey) : null
      const blueprintTargets = new Map<string, { format: string; label: string }>()
      let blueprintHasTitle = false
      if (blueprint) {
        for (const section of blueprint.sections) {
          const format =
            section.block === 'title'
              ? 'title'
              : section.block === 'heading'
                ? `heading${section.level ?? 2}`
                : section.block === 'blockquote'
                  ? 'blockquote'
                  : null
          if (section.block === 'title') blueprintHasTitle = true
          if (format) {
            blueprintTargets.set(normalizeBlueprintText(section.placeholder), {
              format,
              label: BLUEPRINT_FORMAT_LABELS[format] ?? format,
            })
          }
        }
      }
      let firstTextBlockSeen = false

      const doc = editor.state.doc
      const candidates: ScannerSuggestion[] = []
      // Content-hash keys are unique per distinct text + suffix within a scan.
      const seenKeys = new Map<string, number>()
      const wordings = new Map<string, CandidateWording>()
      // Same-role headings collected for the sibling inconsistency sweep.
      const headingClusters = new Map<
        StructuralRole,
        Array<{ pos: number; node: ProseMirrorNode; text: string }>
      >()

      doc.descendants((node, pos) => {
      if (candidates.length >= MAX_SCAN_NODES) return false
      if (node.type.name !== 'paragraph' && node.type.name !== 'heading') return

      const text = node.textContent.trim()
      if (text.length < 4 || text.length > 150) return

      // Skip content that should never be suggested as a heading:
      // list items, table cells, questions, and questionnaire options.
      const $res = doc.resolve(pos)
      for (let d = $res.depth; d >= 0; d--) {
        const name = $res.node(d).type.name
        if (
          name === 'bulletList' || name === 'orderedList' || name === 'listItem' ||
          name === 'table' || name === 'tableRow' || name === 'tableCell' || name === 'tableHeader'
        ) {
          return
        }
      }
      if (/[?？]\s*$/.test(text)) return
      if (/^[a-dA-D][.)]\s/.test(text)) return

      // Collect same-role headings for the sibling inconsistency sweep below.
      const structuralRole = classifyStructuralRole(text)
      if (
        structuralRole === 'heading_1' ||
        structuralRole === 'heading_2' ||
        structuralRole === 'heading_3'
      ) {
        const list = headingClusters.get(structuralRole) ?? []
        if (list.length < 30) list.push({ pos, node, text })
        headingClusters.set(structuralRole, list)
      }

for (const { re, format, confidence } of MARKDOWN_PATTERNS) {
        if (re.test(text)) {
          const key = contentKey(text, format, seenKeys)
          if (!dismissedRef.current.has(key)) {
            candidates.push({
              key,
              format,
              confidence,
              from: pos,
              to: pos + node.nodeSize,
              pageNumber: estimatePageNumber(pos),
              preview: text.slice(0, 60),
            })
          }
          return
        }
      }
      for (const { re, format, confidence, numbered } of HEADING_PATTERNS) {
        if (re.test(text)) {
          if (confidence / 100 < minConfidence) continue
          // A numbered sentence ("3.1 To develop ...") is body text, not a heading.
          if (numbered && !isHeadingLike(text)) continue
          if (node.type.name === 'heading') {
            const level = node.attrs.level as number
            const fmtNum = parseInt(format.replace('heading', ''), 10)
            if (level === fmtNum) return
          }

          const key = contentKey(text, format, seenKeys)
          if (!dismissedRef.current.has(key)) {
            candidates.push({
              key,
              format,
              confidence,
              from: pos,
              to: pos + node.nodeSize,
              pageNumber: estimatePageNumber(pos),
              preview: text.slice(0, 60),
            })
          }
          break
        }
      }

      // Blueprint-derived suggestions for the active preset. Text matching a
      // section placeholder that is not yet styled that way is a strong,
      // deductive signal — no behavior history required.
      if (blueprint && blueprintTargets.size > 0) {
        const target = blueprintTargets.get(normalizeBlueprintText(text))
        const alreadyCandidate = candidates.some((candidate) => candidate.from === pos)
        if (target && !alreadyCandidate && !isStyledAsBlueprintFormat(node, target.format)) {
          const key = contentKey(text, target.format, seenKeys)
          if (!dismissedRef.current.has(key)) {
            candidates.push({
              key,
              format: target.format,
              confidence: 90,
              from: pos,
              to: pos + node.nodeSize,
              pageNumber: estimatePageNumber(pos),
              preview: text.slice(0, 60),
              label: `Format as ${target.label} based on ${blueprint.name} preset`,
            })
          }
        } else if (
          blueprintHasTitle &&
          !firstTextBlockSeen &&
          !target &&
          !alreadyCandidate &&
          node.type.name === 'paragraph' &&
          node.attrs.guide == null &&
          !isStyledAsBlueprintFormat(node, 'title') &&
          text.length <= 120
        ) {
          // The opening line of a preset document is its title.
          const key = contentKey(text, 'title', seenKeys)
          if (!dismissedRef.current.has(key)) {
            candidates.push({
              key,
              format: 'title',
              confidence: 86,
              from: pos,
              to: pos + node.nodeSize,
              pageNumber: estimatePageNumber(pos),
              preview: text.slice(0, 60),
              label: `Format as Title based on ${blueprint.name} preset`,
            })
          }
        }
        firstTextBlockSeen = true
      }
      return true
    })

      // ── Sibling-cluster inconsistency sweep ───────────────────────────
      // Headings of one role should look alike. When 80%+ share a style and a
      // sibling deviates, flag it with the cluster's modal styling captured so
      // accepting reproduces the document standard in one click.
      for (const [role, members] of headingClusters) {
        if (members.length < 2 || candidates.length >= MAX_SCAN_NODES) continue
        const styles = members.map((member) => snapshotBlockStyle(member.node))
        const keys = styles.map(styleSnapshotKey)
        const counts = new Map<string, number>()
        for (const key of keys) counts.set(key, (counts.get(key) ?? 0) + 1)
        let modalKey = ''
        let modalCount = 0
        for (const [key, count] of counts) {
          if (count > modalCount) {
            modalKey = key
            modalCount = count
          }
        }
        if (modalCount === members.length || modalCount / members.length < 0.8) continue
        const modalStyle = styles[keys.indexOf(modalKey)]
        const format =
          role === 'heading_1' ? 'heading1' : role === 'heading_2' ? 'heading2' : 'heading3'
        members.forEach((member, index) => {
          if (keys[index] === modalKey) return
          const key = contentKey(member.text, `inconsistent-${role}`, seenKeys)
          if (dismissedRef.current.has(key)) return
          wordings.set(key, { kind: 'line', fix: clusterFix(modalStyle, styles[index]), lineKind: role as LineKind, presetName: null })
          candidates.push({
            key,
            format,
            confidence: 84,
            from: member.pos,
            to: member.pos + member.node.nodeSize,
            pageNumber: estimatePageNumber(member.pos),
            preview: member.text.slice(0, 60),
            label: lineSuggestionLabel(role as LineKind, 1),
            detail: lineSuggestionDetail(clusterFix(modalStyle, styles[index]), null),
            captures: {
              role,
              bold: modalStyle.bold || undefined,
              italic: modalStyle.italic || undefined,
              fontSize: modalStyle.fontSize ?? undefined,
              textAlign: modalStyle.textAlign !== 'left' ? modalStyle.textAlign : undefined,
            },
            suggestionSource: 'learned',
          })
        })
      }

      // ── Body-text consistency sweep ──────────────────────────────────
      // Imported documents arrive with whatever styling they had. Each body
      // property (bold, italic, size, alignment, line spacing, first-line
      // indent, paragraph spacing) is compared with the value most of the body
      // shares; the active preset answers where the document has no clear
      // majority. The capture carries exactly the differing values, so
      // accepting also removes a stray bold, italic or alignment.
      const rules = presetRulesFor(presetKey)
      const body = findBodyDeviations(doc, rules?.body ?? null)
      for (const deviation of body.deviations.slice(0, MAX_BODY_SUGGESTIONS)) {
        const key = contentKey(deviation.text, 'inconsistent-body_paragraph', seenKeys)
        if (dismissedRef.current.has(key)) continue
        const presetBased = Object.keys(deviation.fix).some((prop) => body.source[prop as keyof typeof body.source] === 'preset')
        const blockStyle = blockStyleFor(deviation.fix)
        const presetName = presetBased && rules ? rules.body.name : null
        wordings.set(key, { kind: 'body', fix: deviation.fix, presetName })
        candidates.push({
          key,
          format: 'paragraph',
          confidence: presetBased ? 78 : 82,
          from: deviation.pos,
          to: deviation.pos + deviation.node.nodeSize,
          pageNumber: estimatePageNumber(deviation.pos),
          preview: deviation.text.slice(0, 60),
          label: bodySuggestionLabel(deviation.fix, 1, ''),
          detail: bodySuggestionDetail(presetName),
          captures: {
            role: 'body_paragraph',
            bold: deviation.fix.bold,
            italic: deviation.fix.italic,
            fontSize: deviation.fix.fontSize,
            textAlign: deviation.fix.textAlign,
            blockStyle: Object.keys(blockStyle).length > 0 ? blockStyle : undefined,
          },
          suggestionSource: 'learned',
        })
      }

      // The whole body against the preset (e.g. every paragraph 11pt where the
      // preset says 12pt): one grouped suggestion, not one per paragraph.
      if (rules && body.presetGaps.length > 0 && body.members.length > 0) {
        const [first, ...rest] = body.members
        const gapKey = body.presetGaps.map((gap) => `${gap.property}:${gap.document}`).join('|')
        const key = contentKey(`${rules.body.name}|${gapKey}`, 'preset-body', seenKeys)
        const sizeGap = body.presetGaps.find((gap) => gap.property === 'effectiveSizePt')
        const blockStyle = blockStyleFor({
          lineHeight: body.presetGaps.find((gap) => gap.property === 'lineHeight')?.preset,
          firstIndentPt: body.presetGaps.find((gap) => gap.property === 'firstIndentPt')?.preset,
        })
        if (!dismissedRef.current.has(key)) {
          candidates.push({
            key,
            format: 'paragraph',
            confidence: 76,
            from: first.pos,
            to: first.pos + first.node.nodeSize,
            pageNumber: estimatePageNumber(first.pos),
            preview: first.text.slice(0, 60),
            label: `Body text has ${body.presetGaps.map(describePresetGap).join(', ')} — apply the ${rules.body.name} body style to all ${body.members.length} paragraphs?`,
            formatGroup: 'preset_body-group',
            groupMembers: rest.map((member) => ({
              from: member.pos,
              to: member.pos + member.node.nodeSize,
              preview: member.text.slice(0, 60),
            })),
            captures: {
              role: 'preset_body',
              fontSize: sizeGap ? sizeGap.preset : undefined,
              blockStyle: Object.keys(blockStyle).length > 0 ? blockStyle : undefined,
            },
            suggestionSource: 'learned',
          })
        }
      }

      // ── Short-line consistency sweep ─────────────────────────────────
      // Title-page lines, front-matter labels, headings of each level and
      // captions should each look alike; the preset answers where the
      // document has no clear majority (e.g. a thesis title page is centered).
      const taken = new Set(candidates.map((candidate) => candidate.from))
      let lineCount = 0
      for (const deviation of findShortLineDeviations(doc, rules?.lines ?? null)) {
        if (lineCount >= MAX_LINE_SUGGESTIONS) break
        if (taken.has(deviation.pos)) continue
        const key = contentKey(deviation.text, `inconsistent-${deviation.group}`, seenKeys)
        if (dismissedRef.current.has(key)) continue
        lineCount += 1
        const level = deviation.node.type.name === 'heading' ? Number(deviation.node.attrs.level) : 0
        const linePreset = deviation.fromPreset && rules ? rules.lines.name : null
        wordings.set(key, { kind: 'line', fix: deviation.fix, lineKind: deviation.group, presetName: linePreset })
        candidates.push({
          key,
          format: level >= 1 && level <= 3 ? `heading${level}` : 'paragraph',
          confidence: deviation.fromPreset ? 78 : 83,
          from: deviation.pos,
          to: deviation.pos + deviation.node.nodeSize,
          pageNumber: estimatePageNumber(deviation.pos),
          preview: deviation.text.slice(0, 60),
          label: lineSuggestionLabel(deviation.group, 1),
          detail: lineSuggestionDetail(deviation.fix, linePreset),
          captures: {
            role: deviation.group,
            bold: deviation.fix.bold,
            italic: deviation.fix.italic,
            fontSize: deviation.fix.sizePt ?? undefined,
            textAlign: deviation.fix.textAlign,
          },
          suggestionSource: 'learned',
        })
      }

      // Drop suggestions the block already satisfies and ones the user already
      // answered. Styling-capture suggestions are judged by their own sweep.
      for (let index = candidates.length - 1; index >= 0; index--) {
        const candidate = candidates[index]
        if (memoryRef.current[candidate.key]) {
          candidates.splice(index, 1)
          continue
        }
        if (candidate.captures) continue
        const block = describeBlock(doc, candidate.from + 1)
        const wrongTitle = candidate.format === 'title' && !isTitleCandidate(doc, candidate.from + 1)
        if (wrongTitle || isFormatSatisfied(block, candidate.format)) candidates.splice(index, 1)
      }

      candidates.sort((a, b) => b.confidence - a.confidence)

      const cards = mergeSameFixCandidates(candidates, wordings, sectionIndex(doc))
      candidates.length = 0
      candidates.push(...cards)

      // Only swap state when the candidate set actually changed: re-setting an
      // identical list re-renders the queue and re-anchors chips for nothing.
      setSuggestions((prev) => {
        if (
          prev.length === candidates.length &&
          prev.every((suggestion, i) => suggestion.key === candidates[i].key)
        ) {
          return prev
        }
        return candidates
      })

      setActiveIdx((prev) => {
        if (prev < 0 && candidates.length > 0) return 0
        if (prev >= candidates.length) return candidates.length > 0 ? 0 : -1
        return prev
      })
    }, 0)
  }, [editor, enabled, estimatePageNumber, minConfidence, presetKey])

  /**
   * Drop every dismissed key so a rescanned document can earn fresh
   * suggestions (guide Bug Fix 3, Step 1: dismissal is temporary, not a
   * permanent blacklist tied to document positions).
   */
  const resetDismissed = useCallback(() => {
    dismissedRef.current.clear()
  }, [])

  /** Transition scanner state based on viewport and active suggestion. */
  useEffect(() => {
    if (!activeSuggestion) {
      setScannerState('Idle_Scanning')
      return
    }

    const view = editor?.view
    if (!view || view.isDestroyed) {
      setScannerState('Idle_Scanning')
      return
    }

    const coords = view.coordsAtPos(activeSuggestion.from)
    const viewportTop = window.scrollY
    const viewportBottom = window.scrollY + window.innerHeight
    const MARGIN = 120
    const inView =
      coords.bottom >= viewportTop - MARGIN &&
      coords.top <= viewportBottom + MARGIN

    setIsTargetInViewport(inView)
    setScannerState(inView ? 'InViewport_Detected' : 'OffScreen_Detected')
  }, [activeSuggestion, editor])

  /** Re-check viewport on scroll so off-screen targets correctly transition. */
  useEffect(() => {
    if (!activeSuggestion || !editor || editor.isDestroyed) return

    let ticking = false
    const onScroll = (): void => {
      if (ticking) return
      ticking = true
      requestAnimationFrame(() => {
        const view = editor.view
        if (view.isDestroyed) { ticking = false; return }
        const coords = view.coordsAtPos(activeSuggestion.from)
        const viewportTop = window.scrollY
        const viewportBottom = window.scrollY + window.innerHeight
        const MARGIN = 120
        const inView =
          coords.bottom >= viewportTop - MARGIN &&
          coords.top <= viewportBottom + MARGIN
        setIsTargetInViewport(inView)
        setScannerState(inView ? 'InViewport_Detected' : 'OffScreen_Detected')
        ticking = false
      })
    }

    window.addEventListener('scroll', onScroll, { passive: true })
    onScroll()
    return () => window.removeEventListener('scroll', onScroll)
  }, [activeSuggestion, editor])

  /** Schedule periodic scanning. */
  useEffect(() => {
    if (!enabled || !editor) return

    const initialTimer = setTimeout(() => {
      void scanDocument()
    }, 3000)

    scanTimerRef.current = setInterval(() => {
      void scanDocument()
    }, SCAN_INTERVAL_MS)

    return () => {
      clearTimeout(initialTimer)
      if (scanTimerRef.current) clearInterval(scanTimerRef.current)
    }
  }, [editor, enabled, scanDocument])

  // Re-sweep shortly after any document edit (accept/reject/typing) so the
  // next suggestion surfaces without waiting for the next interval tick.
  useEffect(() => {
    if (!enabled || !editor) return

    let debounceTimer: ReturnType<typeof setTimeout> | null = null
    const onTransaction = (): void => {
      // Skip mid-composition transactions; the final commit re-schedules.
      if (editor.view.composing) return
      if (debounceTimer) clearTimeout(debounceTimer)
      debounceTimer = setTimeout(() => {
        void scanDocument()
      }, RESCAN_DEBOUNCE_MS)
    }

    editor.on('transaction', onTransaction)
    return () => {
      if (debounceTimer) clearTimeout(debounceTimer)
      editor.off('transaction', onTransaction)
    }
  }, [editor, enabled, scanDocument])

  /** Dismiss a single suggestion (user clicked Ignore). */
  const dismissSuggestion = useCallback((key: string): void => {
    setScannerState('Dismissed')
    for (const memberKey of keysOf(key)) {
      dismissedRef.current.add(memberKey)
      memoryRef.current[memberKey] = 'dismissed'
      rememberSuggestion(documentId, memberKey, 'dismissed')
    }
    setSuggestions((prev) => prev.filter((s) => s.key !== key))
    setActiveIdx((prev) => {
      if (prev < 0) return prev
      return 0
    })
    // After state transition, reset to Idle_Scanning for the next suggestion
    setTimeout(() => setScannerState('Idle_Scanning'), 0)
  }, [documentId, keysOf])

  /** Accept the current suggestion. */
  const acceptSuggestion = useCallback((key: string): void => {
    setScannerState('Accepted')
    // Remembered, so the same block text is never offered this format again
    // even if the accept could not change what the pattern looks at.
    for (const memberKey of keysOf(key)) {
      memoryRef.current[memberKey] = 'accepted'
      rememberSuggestion(documentId, memberKey, 'accepted')
    }
    setSuggestions((prev) => prev.filter((s) => s.key !== key))
    setActiveIdx((prev) => {
      if (prev < 0) return prev
      return 0
    })
    setTimeout(() => setScannerState('Idle_Scanning'), 0)
  }, [documentId, keysOf])

  /** Reject the current suggestion. */
  const rejectSuggestion = useCallback((key: string): void => {
    setScannerState('Rejected')
    for (const memberKey of keysOf(key)) {
      dismissedRef.current.add(memberKey)
      memoryRef.current[memberKey] = 'dismissed'
      rememberSuggestion(documentId, memberKey, 'dismissed')
    }
    setSuggestions((prev) => prev.filter((s) => s.key !== key))
    setActiveIdx((prev) => {
      if (prev < 0) return prev
      return 0
    })
    setTimeout(() => setScannerState('Idle_Scanning'), 0)
  }, [documentId, keysOf])

  /** Dismiss all current suggestions. */
  const dismissAll = useCallback((): void => {
    setScannerState('Dismissed')
    setSuggestions((prev) => {
      for (const s of prev) for (const memberKey of s.memberKeys ?? [s.key]) dismissedRef.current.add(memberKey)
      return []
    })
    setActiveIdx(-1)
    setTimeout(() => setScannerState('Idle_Scanning'), 0)
  }, [])

  /** Select a specific suggestion by key. */
  const selectSuggestion = useCallback(
    (key: string): void => {
      const idx = suggestions.findIndex((s) => s.key === key)
      if (idx >= 0) setActiveIdx(idx)
    },
    [suggestions]
  )

  return {
    suggestions,
    activeSuggestion,
    scannerState,
    isTargetInViewport,
    dismissSuggestion,
    dismissAll,
    resetDismissed,
    selectSuggestion,
    acceptSuggestion,
    rejectSuggestion,
  }
}
