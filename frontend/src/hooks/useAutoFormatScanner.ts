  /** Minimum confidence (0–1) a candidate must exceed to be suggested. */
  minConfidence?: number
  /** Key of the active academic preset; enables blueprint-derived suggestions. */
  presetKey?: string | null
  /** Document id; accepted and dismissed suggestions are remembered per document. */
