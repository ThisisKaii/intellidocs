"""Write MATRIX_CORRECTIONS.md: for every TCASE, the Expected Result in the Chapter 4 matrix next
to the result the suite actually asserts (each test file's docstring), plus its known-bug note.

Usage: python build_matrix_corrections.py <matrix.md> [junit.xml ...]
Optional JUnit reports (pytest --junitxml) add each case's outcome; when a case appears in several
(a module run, then a rerun), the report given later wins.
"""

from __future__ import annotations

import ast
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).parent
ROW = re.compile(r"^\|\s*\*\*(TCASE-\d{3})\*\*\s*\|\s*`([^`]+)`\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|")


def matrix_rows(path: Path) -> dict[str, dict[str, str]]:
    rows = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = ROW.match(line)
        if match:
            case, filename, kind, scenario, expected = match.groups()
            rows[case] = {"file": filename, "kind": kind.strip(), "scenario": scenario.strip(), "expected": expected.strip()}
    return rows


def paragraphs(docstring: str) -> list[str]:
    return [" ".join(block.split()) for block in docstring.split("\n\n") if block.strip()]


def docstring_parts(path: Path) -> dict[str, str]:
    text = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
    blocks = paragraphs(text)[1:]  # the first line is the TCASE header
    expected, bug, notes = [], [], []
    for block in blocks:
        if block.startswith("Known bug"):
            bug.append(block)
            continue
        if block.startswith("Slow by nature"):
            continue
        # "…scenario. Expected (as the app behaves): …" or "…scenario. Intended result: …"
        match = re.search(r"\b(Expected\b|Intended result\b)", block)
        if match:
            if block[: match.start()].strip():
                notes.append(block[: match.start()].strip())
            expected.append(block[match.start():])
        elif expected:
            expected.append(block)  # a paragraph continuing the expected result
        else:
            notes.append(block)
    return {"expected": " ".join(expected), "bug": " ".join(bug), "notes": " ".join(notes)}


def outcomes(reports: list[Path]) -> dict[str, str]:
    result: dict[str, str] = {}
    for report in reports:
        if report.exists():
            result.update(outcomes_of(report))
    return result


def outcomes_of(junit: Path) -> dict[str, str]:
    result = {}
    for case in ET.parse(junit).getroot().iter("testcase"):
        name = case.get("name", "")
        match = re.search(r"tcase_(\d{3})", name)
        if not match:
            continue
        skipped = case.find("skipped")
        if case.find("failure") is not None or case.find("error") is not None:
            state = "FAILED"
        elif skipped is not None:
            state = "xfail (known bug)" if skipped.get("type") == "pytest.xfail" else "skipped"
        else:
            state = "passed"
        result[f"TCASE-{match.group(1)}"] = state
    return result


def main() -> int:
    matrix = matrix_rows(Path(sys.argv[1]))
    states = outcomes([Path(arg) for arg in sys.argv[2:]])
    lines = [
        "# Chapter 4 testing matrix: corrected Expected Results",
        "",
        "Generated by `build_matrix_corrections.py` from the matrix and from each test file's docstring,",
        "which states the result the test asserts against the running app. Where the app has a known",
        "bug, the test asserts the intended result and is marked `xfail(strict=True)` until the fix.",
        "",
    ]
    for case, row in sorted(matrix.items()):
        path = HERE / row["file"]
        if not path.exists():
            lines += [f"## {case} ({row['kind']})", "", f"- Test file `{row['file']}` not written.", ""]
            continue
        parts = docstring_parts(path)
        lines += [f"## {case}: {row['kind']}", "", f"- **Test:** `{row['file']}`" + (f" ({states[case]})" if case in states else "")]
        lines.append(f"- **Matrix Expected Result:** {row['expected']}")
        lines.append(f"- **Corrected Expected Result:** {parts['expected'] or '(as in the matrix)'}")
        if parts["notes"]:
            lines.append(f"- **Notes:** {parts['notes']}")
        if parts["bug"]:
            lines.append(f"- **Known bug:** {parts['bug']}")
        lines.append("")
    (HERE / "MATRIX_CORRECTIONS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(matrix)} cases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
