"""Import fidelity gate: paragraphs on Word's page, for every Word fixture, against a committed baseline.

Word's own layout of each fixture is committed as golden data (tests/e2e/tools/make_word_golden.ps1,
which needs Word). This gate needs no Word: it converts each fixture with the real converter, lays
it out in the real paged editor (the dev editor harness), pairs paragraphs with Word's, and fails
when any fixture has fewer paragraphs on Word's page than its baseline, or a page count further
from Word's.

Run from the repo root with the frontend dev server up:
    ml/venv/Scripts/python tests/e2e/word_gate.py
    ml/venv/Scripts/python tests/e2e/word_gate.py --update-baseline   # deliberate; review the diff
    ml/venv/Scripts/python tests/e2e/word_gate.py --roundtrip         # also reopen from the saved editor JSON
    ml/venv/Scripts/python tests/e2e/word_gate.py --shipped-fonts-only  # as a computer without Office fonts

Exit codes: 0 no regression, 1 regression, 2 the gate could not measure (stale golden, a fixture
that failed to load, frontend down).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections import Counter
from pathlib import Path

from playwright.sync_api import sync_playwright

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))

import fidelity_run as fr  # noqa: E402  (convert, to_payload, wait_for_layout)
from word_alignment import Regression, Score, baseline_from, compare, score, summary_lines  # noqa: E402

FIXTURES = REPO / "tests" / "fixtures" / "import_baselines"
TRUTH_DIR = FIXTURES / "word_truth"
BASELINE = FIXTURES / "word_gate_baseline.json"
DEFAULT_OUT = HERE / "artifacts" / "word_gate"

# Two-column papers are single-column in the editor by design, so Word's pages say nothing about
# the editor's; fidelity_run.py scores them through the IEEE print preview instead.
NOT_GATED = {"ieee_sample_paper"}

# Each top-level text block's page, read from where its first line of text is drawn: the paginator
# draws its page boundary inside the next block's box, so the element's own top is misleading.
# Table cells are left out, as they are on Word's side (see word_alignment).
JS_ROWS = """(pitch) => {
  const pm = document.querySelector('.ProseMirror');
  const top0 = pm.getBoundingClientRect().top;
  const out = [];
  pm.querySelectorAll('p, h1, h2, h3, h4, h5, h6').forEach(el => {
    if (el.closest('.rm-page-header, .rm-page-footer, .rm-page-break, table')) return;
    const text = (el.textContent || '').trim();
    if (!text) return;
    const range = document.createRange(); range.selectNodeContents(el);
    const first = range.getClientRects()[0];
    if (!first) return;
    out.push({ text: text.slice(0, 80), page: Math.floor((first.top - top0 + 1) / pitch) + 1 });
  });
  return out;
}"""


# The font names the editor draws itself on every computer (generated by tools/make_font_metrics.py).
ALIASES_CSS = REPO / "frontend" / "src" / "styles" / "wordFontAliases.css"
# Share of a document's glyphs that may still come from installed fonts with only shipped fonts: rare
# symbols no shipped text font has (check marks, boxes, private-use Symbol/Wingdings characters) fall
# back to whatever symbol font the computer has. Anything above this is a font the app should ship.
SYSTEM_GLYPH_ALLOWANCE = 0.005
GENERIC_FAMILIES = {"serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui"}
# A font-family value runs to the next ';', '"' or '}', except the ';' inside an escaped &quot;.
_FONT_FAMILY_DECL = re.compile(r"(font-family\s*:\s*)((?:&quot;|[^;\"}])+)", re.I)


def shipped_families() -> set[str]:
    """Lower-cased family names the editor ships: the Word-name aliases."""
    names = re.findall(r"font-family:\s*'([^']+)'", ALIASES_CSS.read_text(encoding="utf-8"))
    if not names:
        raise GateError(f"no font aliases in {ALIASES_CSS.relative_to(REPO)}")
    return {name.lower() for name in names}


def local_first_fonts() -> set[str]:
    """Lower-cased installed fonts the aliases use before their stand-in (`src: local(...)`): drawn by the
    computer's copy where there is one, by the stand-in or the system's emoji font elsewhere."""
    css = ALIASES_CSS.read_text(encoding="utf-8")
    return {name.lower() for name in re.findall(r"local\('([^']+)'\)", css)}


def shipped_fonts_only(payload: dict, shipped: set[str], dropped: Counter) -> dict:
    """The payload as a computer with none of the document's fonts installed would lay it out: every
    font-family stack keeps only the families the editor ships (and generic ones)."""

    def reduce(match: re.Match) -> str:
        kept = []
        for item in match.group(2).split(","):
            name = item.strip().replace("&quot;", "").strip("'\" \\")
            if name.lower() in shipped or name.lower() in GENERIC_FAMILIES:
                kept.append(f"'{name}'" if " " in name else name)
            elif name:
                dropped[name] += 1
        return match.group(1) + (", ".join(kept) or "serif")

    def walk(value):
        if isinstance(value, str):
            return _FONT_FAMILY_DECL.sub(reduce, value)
        if isinstance(value, list):
            return [walk(item) for item in value]
        if isinstance(value, dict):
            return {key: walk(item) for key, item in value.items()}
        return value

    return walk(payload)


def platform_fonts(context, page) -> dict[str, dict]:
    """Which font files drew the document's text: {family: {"glyphs": n, "custom": bool}}, where custom
    means an @font-face the app declares rather than whatever the computer has installed. Each text
    block reports the fonts of its inline text, so the blocks are queried directly; nothing is marked
    (ProseMirror reverts attribute changes it did not make)."""
    cdp = context.new_cdp_session(page)
    cdp.send("DOM.enable")
    cdp.send("CSS.enable")
    root = cdp.send("DOM.getDocument", {"depth": -1})["root"]["nodeId"]
    used: dict[str, dict] = {}
    selector = ", ".join(f".ProseMirror {tag}" for tag in ("p", "h1", "h2", "h3", "h4", "h5", "h6", "pre", "figcaption"))
    blocks = cdp.send("DOM.querySelectorAll", {"nodeId": root, "selector": selector})["nodeIds"]
    for node in blocks:
        for font in cdp.send("CSS.getPlatformFontsForNode", {"nodeId": node})["fonts"]:
            entry = used.setdefault(font["familyName"], {"glyphs": 0, "custom": font["isCustomFont"]})
            entry["glyphs"] += int(font["glyphCount"])
    if not used:
        raise GateError("the font check found no text in the editor")
    return used


# Section breaks the editor holds: each must carry the section properties the converter wrote (Python
# writes them, frontend/src/lib/sectionProps.ts reads them; a mismatch would silently become null).
JS_SECTION_BREAKS = """() => {
  const out = [];
  window.__editor.state.doc.descendants((node) => {
    if ((node.type.name === 'pageBreak' || node.type.name === 'sectionMark') && node.attrs.section !== null) {
      out.push({ type: node.type.name, section: node.attrs.section, props: node.attrs.sectionProps !== null });
    }
  });
  return out;
}"""


class GateError(Exception):
    """The gate could not measure: a reason to stop, not a regression."""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def golden_files(only: str | None) -> list[tuple[str, Path, dict]]:
    """(name, fixture path, truth) for every gated fixture, refusing truth recorded for another file."""
    if not TRUTH_DIR.is_dir():
        raise GateError(f"no golden data in {TRUTH_DIR}: run tests/e2e/tools/make_word_golden.ps1 on a machine with Word")
    chosen = []
    for path in sorted(TRUTH_DIR.glob("*.json")):
        name = path.stem
        if name in NOT_GATED or (only and only.lower() not in name.lower()):
            continue
        truth = json.loads(path.read_text(encoding="utf-8-sig"))
        fixture = FIXTURES / "documents" / f"{name}.docx"
        if not fixture.is_file():
            raise GateError(f"golden {path.name} has no fixture {fixture.name}")
        if truth.get("sha256") != sha256(fixture):
            raise GateError(f"golden {path.name} was recorded for a different {fixture.name}: re-run make_word_golden.ps1")
        chosen.append((name, fixture, truth))
    if not chosen:
        raise GateError("no fixture selected")
    return chosen


# PagedEditor logs this when saved JSON does not fit the editor schema and it falls back to the HTML.
JSON_REJECTED = "Saved editor JSON does not fit the editor schema"


def measure(
    browser, web: str, payload: dict, keep_json: bool = False, fonts: dict | None = None
) -> tuple[list[dict], int, dict | None]:
    """The editor's rows and page count for one converted fixture, laid out the way the Document page
    does, and (with keep_json) the editor's JSON as autosave would store it. A `fonts` dict is filled
    with the font files that drew the text (see platform_fonts)."""
    context = browser.new_context(viewport={"width": 1300, "height": 1250})
    page = context.new_page()
    rejected: list[str] = []
    page.on("console", lambda message: rejected.append(message.text) if JSON_REJECTED in message.text else None)
    page.route("**fonts.googleapis.com**", lambda r: r.abort())
    page.route("**fonts.gstatic.com**", lambda r: r.abort())
    page.add_init_script("window.__FIDELITY__ = " + json.dumps(payload))
    try:
        page.goto(f"{web}/dev/editor-harness", wait_until="domcontentloaded")
        page.wait_for_selector(".rm-pages-wrapper", state="attached", timeout=90000)
        fr.wait_for_layout(page)
        page.evaluate("document.fonts.ready.then(() => true)")
        layout = fr.wait_for_layout(page)
        rows = page.evaluate(JS_ROWS, layout["pageH"] + 40)
        unreadable = [b for b in page.evaluate(JS_SECTION_BREAKS) if not b["props"]]
        if unreadable:
            raise GateError(f"section breaks reached the editor without readable section properties: {unreadable[:5]}")
        if rejected:
            raise GateError(f"the saved JSON was rejected on reopen: {rejected[0]}")
        saved = page.evaluate("window.__editor.getJSON()") if keep_json else None
        if fonts is not None:
            fonts.update(platform_fonts(context, page))
        return rows, int(layout["pages"]), saved
    finally:
        context.close()


def run(web: str, only: str | None, roundtrip: bool = False, shipped_only: bool = False) -> dict[str, Score]:
    """Measure every selected fixture. With roundtrip, each is also reopened from the editor JSON its
    first open would save, and must score exactly as that first open did (a `name (reopened)` entry)."""
    scores: dict[str, Score] = {}
    shipped = shipped_families() if shipped_only else set()
    via_alias = local_first_fonts() if shipped_only else set()
    dropped: Counter = Counter()
    system_drawn: dict[str, dict] = {}
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=True, channel="chrome", args=["--font-render-hinting=none"])
        try:
            for name, fixture, truth in golden_files(only):
                print(f"{name} ...", flush=True)
                payload = fr.to_payload(fr.convert(fixture))
                fonts: dict | None = None
                if shipped_only:
                    payload = shipped_fonts_only(payload, shipped, dropped)
                    fonts = {}
                try:
                    rows, pages, saved = measure(browser, web, payload, keep_json=roundtrip, fonts=fonts)
                    scores[name] = score(truth, rows, pages)
                    if roundtrip:
                        rows, pages, _ = measure(browser, web, {**payload, "json": saved})
                        scores[f"{name} (reopened)"] = score(truth, rows, pages)
                    if fonts is not None:
                        glyphs = {family: use["glyphs"] for family, use in fonts.items()}
                        system = {
                            family: use["glyphs"]
                            for family, use in fonts.items()
                            if not use["custom"] and family.lower() not in via_alias
                        }
                        share = sum(system.values()) / max(1, sum(glyphs.values()))
                        print(f"  fonts drawn: {dict(sorted(glyphs.items(), key=lambda kv: -kv[1]))}")
                        if system:
                            print(f"  from installed fonts: {system} ({share:.2%} of glyphs)")
                        if share > SYSTEM_GLYPH_ALLOWANCE:
                            system_drawn[name] = system
                except GateError:
                    raise
                except Exception as error:  # a fixture that cannot load is a gate failure, not a skip
                    raise GateError(f"{name} could not be measured: {type(error).__name__}: {error}") from error
        finally:
            browser.close()
    if shipped_only:
        print("\nfont names removed (not shipped):", dict(dropped.most_common(12)) or "none")
        if system_drawn:
            raise GateError(
                "with only shipped fonts, text was still drawn by installed fonts (the layout would differ "
                f"by computer): {system_drawn}"
            )
        print(
            "text was drawn by fonts the app ships (Cambria and Segoe UI Symbol through aliases that prefer an "
            f"installed copy), apart from at most {SYSTEM_GLYPH_ALLOWANCE:.1%} rare symbols per document"
        )
    return scores


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--web", default="http://localhost:5173", help="frontend dev server serving /dev/editor-harness")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--only", help="measure only fixtures whose name contains this text (no baseline update)")
    parser.add_argument("--update-baseline", action="store_true", help="record today's scores as the baseline")
    parser.add_argument(
        "--shipped-fonts-only",
        action="store_true",
        help="lay out as a computer without the documents' fonts would: keep only fonts the editor ships",
    )
    parser.add_argument(
        "--roundtrip",
        action="store_true",
        help="also reopen every fixture from the editor JSON it would save; it must score as the first open did",
    )
    args = parser.parse_args(argv)
    if args.update_baseline and (args.only or args.roundtrip or args.shipped_fonts_only):
        parser.error("--update-baseline records every fixture's first open as is; drop the other options")

    try:
        scores = run(args.web, args.only, args.roundtrip, args.shipped_fonts_only)
    except GateError as error:
        print(f"GATE ERROR: {error}")
        return 2

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "summary.json").write_text(json.dumps({n: s.as_dict() for n, s in scores.items()}, indent=1), encoding="utf-8")
    table = "\n".join(summary_lines(scores))
    (args.out / "summary.txt").write_text(table + "\n", encoding="utf-8")
    print("\n" + table)

    if args.update_baseline:
        BASELINE.write_text(json.dumps(baseline_from(scores), indent=1) + "\n", encoding="utf-8")
        print(f"\nbaseline written to {BASELINE.relative_to(REPO)}: review the diff before committing it")
        return 0

    if not BASELINE.is_file():
        print(f"\nGATE ERROR: no baseline at {BASELINE.relative_to(REPO)}: run with --update-baseline")
        return 2
    baseline = json.loads(BASELINE.read_text(encoding="utf-8"))
    reopened = {name: s for name, s in scores.items() if name.endswith(" (reopened)")}
    scores = {name: s for name, s in scores.items() if name not in reopened}
    if args.only:
        baseline = {name: entry for name, entry in baseline.items() if name in scores}
    regressions = compare(scores, baseline)
    for name, again in reopened.items():
        first = scores[name.removesuffix(" (reopened)")]
        if again.as_dict() != first.as_dict():
            regressions.append(Regression(
                name,
                "reopening from the saved JSON changed the layout: paragraphs on Word's page "
                f"{first.same_page} -> {again.same_page}, pages {first.editor_pages} -> {again.editor_pages}",
            ))
    if regressions:
        print("\nREGRESSION")
        for regression in regressions:
            print(f"  {regression.name}: {regression.reason}")
        return 1
    print("\nno regression against the baseline")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
